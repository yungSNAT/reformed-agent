//! Parity case for `generate-skill-docs`: every file it writes must match,
//! byte for byte, what the retired Python script wrote for the same fixture
//! (`tests/fixtures/skill-docs/expected`), apart from the absolute repository
//! path in its output and the generated-page note, which now names the Rust
//! command.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const OLD_NOTE: &str = "by website/scripts/generate-skill-docs.py.";
const NEW_NOTE: &str = "by `cargo run -p hermes-parity-tools -- generate-skill-docs`.";

fn fixture() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/skill-docs")
}

fn copy_tree(from: &Path, to: &Path) {
    fs::create_dir_all(to).unwrap();
    for entry in fs::read_dir(from).unwrap() {
        let entry = entry.unwrap();
        let target = to.join(entry.file_name());
        if entry.file_type().unwrap().is_dir() {
            copy_tree(&entry.path(), &target);
        } else {
            fs::copy(entry.path(), &target).unwrap();
        }
    }
}

fn files(root: &Path, dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            files(root, &path, out);
        } else {
            out.push(path.strip_prefix(root).unwrap().to_path_buf());
        }
    }
}

#[test]
fn generate_skill_docs_matches_the_python_generator() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("run");
    copy_tree(&fixture().join("tree"), &root);
    fs::create_dir_all(root.join("website/docs/reference")).unwrap();
    let root = fs::canonicalize(&root).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_hermes-parity-tools"))
        .args(["generate-skill-docs", "--repo-root"])
        .arg(&root)
        .output()
        .unwrap();
    let stdout = String::from_utf8(output.stdout).unwrap();
    assert!(
        output.status.success(),
        "stdout: {stdout}\nstderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let shown = root.display().to_string();
    let shown = shown
        .strip_prefix(r"\\?\")
        .unwrap_or(&shown)
        .replace('\\', "/");
    assert_eq!(
        stdout.replace('\\', "/").replace(&shown, "<ROOT>"),
        fs::read_to_string(fixture().join("expected/stdout")).unwrap()
    );

    let expected_root = fixture().join("expected");
    let mut expected = Vec::new();
    files(
        &expected_root,
        &expected_root.join("website"),
        &mut expected,
    );
    let mut written = Vec::new();
    files(&root, &root.join("website"), &mut written);
    expected.sort();
    written.sort();
    assert_eq!(written, expected);
    for rel in expected {
        let want = fs::read_to_string(expected_root.join(&rel))
            .unwrap()
            .replace(OLD_NOTE, NEW_NOTE)
            .replace(
                "regenerated by `website/scripts/generate-skill-docs.py`.",
                "regenerated by `cargo run -p hermes-parity-tools -- generate-skill-docs`.",
            );
        let got = fs::read_to_string(root.join(&rel)).unwrap();
        assert_eq!(got, want, "{}", rel.display());
    }
}
